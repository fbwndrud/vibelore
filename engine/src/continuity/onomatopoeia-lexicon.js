/**
 * OnomatopoeiaLexicon — Korean 의성어 (sound) / 의태어 (motion/state).
 *
 * Categorical tagging for layer-1 quality scan (N8 overuse: count /
 * wordCount → SOFT FLAG `ONOMATOPOEIA_OVERUSE`).
 */
export class DefaultOnomatopoeiaLexicon {
    entries;
    byCategoryMap;
    constructor(seed) {
        this.entries = new Map();
        this.byCategoryMap = new Map();
        const source = seed ?? KO_ONOMATOPOEIA_SEED;
        for (const entry of source) {
            this.entries.set(entry.word, entry);
            const arr = this.byCategoryMap.get(entry.category) ?? [];
            arr.push(entry);
            this.byCategoryMap.set(entry.category, arr);
        }
    }
    lookup(word) {
        return this.entries.get(word);
    }
    byCategory(c) {
        return this.byCategoryMap.get(c) ?? [];
    }
    all() {
        return [...this.entries.values()];
    }
}
