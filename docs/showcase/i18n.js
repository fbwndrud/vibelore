/* vibelore 제작 예시 — 한국어/영어 UI 전환과 번역 사전.
 *
 * 모든 페이지가 <head>에서 이 파일 하나를 읽는다. 사전(EN)은 한국어 원문 → 영어로 적는다.
 * - 정적 HTML: I18N.apply()가 본문 텍스트 노드와 alt·title·aria-label을 원문 그대로 찾아 바꾼다.
 *   <a>·<b>가 섞인 문단은 data-i18n="키"를 달고 EN[키]에 영어 HTML을 둔다.
 *   lang 속성이나 translate="no"가 붙은 요소(작품 제목, 원문 인용)는 건드리지 않는다.
 * - 스크립트가 만드는 문구: T('한국어 {n}', { n }) 형태로 부른다. 사전에 없으면 원문이 나온다.
 * - 언어 결정 순서: ?lang= → localStorage → navigator.language(한국어면 ko, 아니면 en).
 * 작품 본문(소설·웹툰 대사)은 번역하지 않는다.
 */
(function () {
  'use strict';
  var SUPPORTED = ['ko', 'en'];
  var STORE_KEY = 'vibelore.lang';
  var params = null;
  try { params = new URLSearchParams(location.search); } catch (e) { params = null; }
  var fromParam = params && SUPPORTED.indexOf(params.get('lang')) >= 0 ? params.get('lang') : null;

  function stored() { try { var v = localStorage.getItem(STORE_KEY); return SUPPORTED.indexOf(v) >= 0 ? v : null; } catch (e) { return null; } }
  function remember(v) { try { localStorage.setItem(STORE_KEY, v); } catch (e) { /* 저장 불가(사생활 보호 모드 등) */ } }
  function browser() { var n = (navigator.languages && navigator.languages[0]) || navigator.language || ''; return /^ko\b/i.test(n) ? 'ko' : 'en'; }

  var lang = fromParam || stored() || browser();
  if (fromParam) remember(fromParam);
  document.documentElement.lang = lang;

  var EN = {};
  var missing = [];
  var HANGUL = /[가-힣]/;

  function fill(s, vars) {
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? String(vars[k]) : m; });
  }
  function t(s, vars) {
    if (s == null) return s;
    var src = String(s);
    if (lang === 'en') {
      var hit = EN[src];
      if (hit == null) { var norm = src.trim().replace(/\s+/g, ' '); hit = EN[norm]; }
      if (hit != null) return fill(hit, vars);
      if (HANGUL.test(src) && missing.indexOf(src) < 0) missing.push(src);
    }
    return fill(src, vars);
  }
  function has(s) { return EN[s] != null; }

  var SKIP = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, TEXTAREA: 1 };
  var LITERAL = { CODE: 1, PRE: 1 };
  var ATTRS = ['title', 'alt', 'aria-label', 'placeholder'];
  function translateAttrs(node) {
    for (var i = 0; i < ATTRS.length; i++) {
      var a = node.getAttribute(ATTRS[i]);
      if (a && HANGUL.test(a)) { var v = t(a); if (v !== a) node.setAttribute(ATTRS[i], v); }
    }
  }
  function walk(node) {
    if (node.nodeType === 3) {
      var raw = node.nodeValue; var key = raw.trim().replace(/\s+/g, ' ');
      if (key && HANGUL.test(key)) {
        var v = t(key);
        if (v !== key) node.nodeValue = raw.replace(/^(\s*)[\s\S]*?(\s*)$/, function (m, a, b) { return a + v + b; });
      }
      return;
    }
    if (node.nodeType !== 1 || SKIP[node.tagName]) return;
    if (node !== document.documentElement && (node.hasAttribute('lang') || node.getAttribute('translate') === 'no')) return;
    translateAttrs(node);
    var k = node.getAttribute('data-i18n');
    if (k) { if (EN[k] != null) node.innerHTML = EN[k]; else if (missing.indexOf(k) < 0) missing.push(k); return; }
    if (LITERAL[node.tagName]) return;
    for (var c = node.firstChild; c; c = c.nextSibling) walk(c);
  }
  // 정적 마크업을 한 번 번역한다. 페이지 스크립트가 데이터를 그리기 전에 부른다.
  function apply(root) {
    if (lang !== 'en') return;
    if (document.title && HANGUL.test(document.title)) document.title = t(document.title);
    var md = document.querySelector('meta[name="description"]');
    if (md && HANGUL.test(md.content)) md.content = t(md.content);
    walk(root || document.body);
  }

  function urlFor(v) {
    var u = new URL(location.href);
    u.searchParams.set('lang', v);
    return u.pathname + u.search + u.hash;
  }
  // 언어 전환 링크. 누르면 ?lang=을 붙여 다시 연다(공유 가능한 주소).
  function toggle() {
    var box = document.createElement('span');
    box.className = 'lang-tog';
    box.setAttribute('role', 'group');
    box.setAttribute('aria-label', lang === 'en' ? 'Language' : '언어');
    [['ko', '한국어'], ['en', 'EN']].forEach(function (p) {
      var a = document.createElement('a');
      a.href = urlFor(p[0]); a.textContent = p[1]; a.lang = p[0]; a.hreflang = p[0];
      if (p[0] === 'en') a.title = 'English';
      if (p[0] === lang) { a.className = 'on'; a.setAttribute('aria-current', 'true'); }
      a.addEventListener('click', function (ev) { ev.preventDefault(); remember(p[0]); location.href = urlFor(p[0]); });
      box.appendChild(a);
    });
    return box;
  }

  // ?lang=으로 들어온 경우, 같은 사이트 안 링크에도 언어를 이어 붙인다(저장소를 못 쓰는 브라우저 대비).
  if (fromParam) {
    document.addEventListener('click', function (ev) {
      var a = ev.target && ev.target.closest ? ev.target.closest('a[href]') : null;
      if (!a || a.closest('.lang-tog') || a.target === '_blank') return;
      var href = a.getAttribute('href');
      if (!href || /^(#|mailto:|javascript:)/i.test(href)) return;
      var u; try { u = new URL(href, location.href); } catch (e) { return; }
      if (u.origin !== location.origin || /\.(json|webp|png|jpe?g)$/i.test(u.pathname) || u.searchParams.has('lang')) return;
      u.searchParams.set('lang', fromParam); a.href = u.href;
    }, true);
  }

  var css = document.createElement('style');
  css.textContent = '.lang-tog{display:inline-flex;align-items:center;gap:2px;margin-left:auto;flex-shrink:0;font-size:12px;line-height:1;position:sticky;right:0;background:inherit;padding-left:8px}'
    + '.lang-tog a{padding:5px 8px;border-radius:12px;text-decoration:none;color:inherit;opacity:.72;white-space:nowrap}'
    + '.lang-tog a:hover{opacity:1}.lang-tog a.on{opacity:1;font-weight:700;box-shadow:inset 0 0 0 1px currentColor}'
    + 'html[lang=en] .lede,html[lang=en] .hd,html[lang=en] .hcard b{word-break:normal}';
  (document.head || document.documentElement).appendChild(css);

  function num(n, opts) { return Number(n).toLocaleString(lang === 'ko' ? 'ko-KR' : 'en-US', opts); }

  window.I18N = { lang: lang, t: t, has: has, apply: apply, toggle: toggle, num: num, missing: missing, dict: EN, add: function (o) { for (var k in o) EN[k] = o[k]; } };
  window.T = t;
})();

